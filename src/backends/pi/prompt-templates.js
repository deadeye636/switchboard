// backends/pi/prompt-templates.js — the handoff and plan conventions, written as Pi prompt templates (#569).
//
// Pi loads prompt templates from `--prompt-template <path>` (a file or a directory, repeatable) as
// well as from its own `<agentDir>/prompts/` and `<project>/.pi/prompts/`, and offers each as
// `/<filename>`. This file composes the two the app ships. The FORMAT is Pi's, so the knowledge stays
// in the backend folder and the core only ever handles the finished text.
//
// **The app passes them as a flag; it does not write into Pi's configuration directory.** Each spawn
// gets a directory of its own under the app's own data, exactly as `live-binding.js` does with
// `--extension`. What that buys, and what it costs, is the spec record for #569 — the short version is
// that nothing here has to be adopted, versioned, reconciled or cleaned up out of somebody else's
// home, and in exchange a Pi run this app did not start sees none of it.
//
// **The text is not the app's prompt text, and that is deliberate.** `DEFAULT_HANDOFF_PROMPT` in
// `src/renderer/session/session-health.js` says "Return only a markdown handoff" because the APP
// captures the answer and writes the packet; typed as `/handoff` inside Pi nobody captures anything,
// so the agent has to be told to write the file itself. That prompt also carries per-session
// placeholders (`{goal}`, `{sessionId}`, `{metrics}`) a static file cannot fill, and the plan prompt
// uses the absolute `{planPath}`, which is empty when there is no project.
//
// Three things about Pi's own reader decide the shape below, all read out of
// `dist/core/prompt-templates.js`, `dist/core/resource-loader.js` and `dist/utils/frontmatter.js` in
// Pi 0.84.4 rather than assumed:
//
//   1. **Frontmatter is real YAML and unknown keys are ignored.** `loadTemplateFromFile` reads
//      `description` and `argument-hint` and nothing else, so the label below can live there.
//      Invalid YAML, though, makes the whole load return null inside a bare `catch` — a malformed
//      block would remove the command with no diagnostic anywhere, which is why every value written
//      here is quoted and none of them carries user-supplied text.
//   2. **There is no escape for argument substitution.** `substituteArgs` runs one regex over the
//      body and honours no `\$` and no `$$`. A directory name holding `$1`, `$@`, `$ARGUMENTS` or
//      `${…}` therefore cannot be represented in a template at all — see `hasArgumentSubstitution`,
//      which exists so the caller can say so instead of writing a template that mangles the path.
//   3. **A template passed on the command line LOSES a name collision.** `mergePaths` appends the
//      CLI paths after everything discovered (`resource-loader.js:652-664`) and `dedupePrompts` keeps
//      the FIRST entry per name, so a `plan.md` the user keeps in `~/.pi/agent/prompts/` or in a
//      trusted project wins over ours. That is the intended answer to "I want a different /plan" and
//      it is why this feature needs no way to edit these files: write your own, and it takes over.
'use strict';

const fs = require('fs');
const path = require('path');

// Pi's substitution grammar, copied verbatim from `substituteArgs` in Pi 0.84.4. Anything this
// matches is rewritten before the agent sees it, and there is no way to quote it.
const ARG_SUBSTITUTION = /\$\{(?:\d+|ARGUMENTS|@):-[^}]*\}|\$\{@:\d+(?::\d+)?\}|\$(?:ARGUMENTS|@|\d+)/;

// A LABEL, not a contract. These files live for one spawn, in a directory the app made and deletes
// again, so nothing reads them back to decide whether they may be replaced — the ownership marker and
// its body digest that earlier revisions of this feature carried were for a route that wrote into
// Pi's own configuration directory, and that route was not taken.
//
// What is left says where a file came from if one is ever found loose, which is the same job as the
// "Generated by Switchboard for one Pi spawn. Safe to delete." first line in `live-binding.js`. It
// goes in the frontmatter rather than the body because Pi strips the frontmatter before the body
// reaches the model — a note in the body would be part of the prompt.
const MARKER_KIND = 'x-switchboard-template';
const MARKER_NOTE = 'x-switchboard-note';
const NOTE_TEXT = 'Generated by Switchboard for one Pi session. Safe to delete.';

// `$@` on its own line: `/handoff only the open questions` reaches the agent as extra guidance, and
// an invocation with no arguments leaves nothing behind.
const ARGUMENT_TAIL = '$@';

const TEMPLATES = {
  handoff: {
    fileName: 'handoff.md',
    dirKey: 'handoffDir',
    description: 'Summarise this session and write a handoff packet',
    argumentHint: '[what to focus on]',
    // The summarising role, not the reading one (P8): `/handoff` is typed inside a live session, and
    // the reading prompt needs a transcript path and a fresh session to be worth anything.
    // The shape is the one `docs/handoffs-convention.md` describes.
    body: (dir) => `Summarise the state of this session and write a handoff packet for whoever picks the work up next.

Use your current session context to describe the actual work state. Do not continue implementing.

Write the packet as a markdown file in ${dir}, named <date>-<slug>.md — for example
2026-08-24-tariff-end-date.md. Nothing depends on the name.

The packet's title is its first heading, and a header block carries the rest:

    # Tariff end date — the successor implies it

    > created: <the current time, ISO 8601> · backend: pi

Then these sections:

- Goal
- Completed
- In progress
- Blocked or risky
- Important files/context
- Next actions
- Avoid

${ARGUMENT_TAIL}
`,
  },

  plan: {
    fileName: 'plan.md',
    dirKey: 'planDir',
    description: 'Write a plan for the work we are about to do',
    argumentHint: '[what the plan is for]',
    // The mirror of the app's plan prompt, in the shape `docs/plans-convention.md` describes. `{today}`
    // has no counterpart here — a prompt template computes nothing — so the date is asked for in words.
    body: (dir) => `Write a plan for the work we are about to do. Do not implement anything yet.

Write it as a markdown file in ${dir}, named <date>-<slug>.md — for example
2026-08-20-tariff-end-date.md. Nothing depends on the name.

The plan's title is its first heading, and a header block carries the state:

    # Remove the end date from the tariff — it follows from the successor

    > status: active · updated: <today's date>

status is one of active, done, superseded or blocked; a blocked plan says what would unblock it.
updated is the day you write it.

Then the plan itself: what is to be done, in the order it should happen, and what would show that it
worked. Keep it short enough to be read before the work starts.

${ARGUMENT_TAIL}
`,
  },
};

const KINDS = Object.keys(TEMPLATES);

// Does this text hold something Pi would rewrite as an argument? Asked about the directory name
// before a template is composed: there is no escape, so the honest answer is to refuse the template
// and say why, not to write one that names a directory the agent will never find.
function hasArgumentSubstitution(text) {
  return ARG_SUBSTITUTION.test(String(text == null ? '' : text));
}

// The finished file for one kind.
//
// `dirName` is the project-relative name from `src/app/convention-dirs.js` ('.handoffs', '.plans') —
// relative and not absolute on purpose: the agent runs in the project, and an absolute path would put
// this machine's directory layout into a file that gets read out loud.
//
// Answers `{ ok: false, reason }` rather than a bare null, so the one caller does not have to
// re-derive WHICH rule refused by calling `hasArgumentSubstitution` a second time itself. One rule,
// one reading (reflex 12) — and the caller has something to put in front of the user.
function buildPromptTemplate(kind, dirName) {
  const spec = TEMPLATES[kind];
  if (!spec) return { ok: false, reason: 'unknown-kind' };

  // `conventionDirs` spells a relative name with the platform's own separator, so on Windows an
  // absolute setting inside the project comes back as `docs\plans`. Forward slashes are what both
  // convention documents write and what an agent reads the same way on either platform — and a lone
  // backslash in prose is one typo away from reading as an escape.
  const dir = String(dirName == null ? '' : dirName).trim().replace(/\\/g, '/');
  if (!dir) return { ok: false, reason: 'no-directory' };
  // There is no escape for this in Pi, so the honest answer is to compose nothing and say why.
  if (hasArgumentSubstitution(dir)) return { ok: false, reason: 'argument-substitution' };

  const body = spec.body(dir);
  const frontmatter = [
    '---',
    `description: ${JSON.stringify(spec.description)}`,
    `argument-hint: ${JSON.stringify(spec.argumentHint)}`,
    `${MARKER_KIND}: ${JSON.stringify(kind)}`,
    `${MARKER_NOTE}: ${JSON.stringify(NOTE_TEXT)}`,
    '---',
    '',
  ].join('\n');

  return { ok: true, kind, fileName: spec.fileName, command: `/${kind}`, text: frontmatter + body };
}

// The option that switches this off, read HERE and nowhere else. The core hands the session's resolved
// options to the hook and names neither this key nor this backend — that is the whole point of the seam
// (reflex 5). `!== false` rather than a truthy test because the field defaults ON and the cascade only
// stores what somebody marked as set, so "nobody said anything" has to mean yes.
const OPTION_ID = 'conventionPrompts';

/**
 * Write both templates for one spawn and say how to hand them to Pi.
 *
 * Modelled on `writeBindingExtension` in `live-binding.js`, which solves the same problem one flag
 * along: a file this app generates for a single run, under the app's own data directory, never in the
 * user's CLI configuration.
 *
 * **A raw `fs.writeFileSync` is correct here and CLAUDE.md reflex 11 does not apply.** That rule exists
 * because a file a CLI reads is usually a file somebody else also writes — so a write needs a baseline
 * compare, an atomic rename and the file's own line endings. None of that has a subject here: the
 * directory is made fresh for this spawn, nothing else can be holding these paths, and there is no
 * previous content to preserve or to race against. `live-binding.js` makes the same call for the same
 * reason.
 *
 * `dirs` is `{ handoffDir, planDir }` as `src/app/convention-dirs.js` resolved them for this session's
 * project — project-relative names, already guarded. Returns `null` for anything it cannot do, because
 * a launch must never fail over this.
 */
// The tag becomes a path SEGMENT, and `removePromptTemplates` deletes that path recursively — so a tag
// holding a separator or `..` would put the removal somewhere nobody chose. It is `crypto.randomUUID()`
// at every call site today and cannot be any of those, which is exactly the argument that stops being
// true the first time somebody passes something else. A plain token is all this ever needs
// (CLAUDE.md reflex 13: never let a name that becomes a path decide where a write or a delete lands).
const SAFE_TAG = /^[A-Za-z0-9][A-Za-z0-9_-]{0,127}$/;
// One spelling for the directory this module owns, so the writer and the remover cannot disagree
// about what "a directory of ours" looks like.
const DIR_PREFIX = 'pi-prompts-';

function writePromptTemplates({ dir, tag, dirs, options, log } = {}) {
  if (!dir || !tag) return null;
  if (!SAFE_TAG.test(String(tag))) {
    if (log && typeof log.warn === 'function') log.warn('[pi-prompts] refusing a tag that is not a plain token');
    return null;
  }
  if (options && options[OPTION_ID] === false) return null;

  const files = [];
  for (const kind of KINDS) {
    const built = buildPromptTemplate(kind, (dirs || {})[TEMPLATES[kind].dirKey]);
    if (!built.ok) {
      // The only reason a caller sees today is a directory name Pi would rewrite as an argument, and
      // there is no escape for it — so this command is not offered rather than offered pointing at a
      // directory the agent will never find. The other kind is still written.
      if (log && typeof log.warn === 'function') {
        log.warn(`[pi-prompts] /${kind} not offered: ${built.reason}`);
      }
      continue;
    }
    files.push(built);
  }
  if (!files.length) return null;

  // One directory per spawn, so two sessions in two projects cannot hand each other their neighbour's
  // convention directories, and so cleanup can remove a directory rather than pick files out of a
  // shared one.
  const target = path.join(dir, DIR_PREFIX + tag);
  try {
    fs.mkdirSync(target, { recursive: true });
    for (const file of files) fs.writeFileSync(path.join(target, file.fileName), file.text, 'utf8');
  } catch (err) {
    if (log && typeof log.warn === 'function') log.warn(`[pi-prompts] could not write: ${err.message}`);
    return null;
  }

  if (log && typeof log.debug === 'function') {
    log.debug(`[pi-prompts] wrote ${files.map(f => f.command).join(' ')} to ${target}`);
  }
  return { args: ['--prompt-template', target], cleanup: target };
}

// Removes a directory this module made, and nothing else.
//
// The basename check is the point. This is the only destructive call in the file and it is a
// RECURSIVE delete of a path handed in from outside — today both callers pass back the `cleanup` they
// were given, but "every caller is careful" is a property that holds until somebody writes a third
// one. `src/app/path-containment.js` is the app's answer to a containment question and a backend
// folder may not import from `src/app/**` (`.claude/rules/backends.md`), so the guarantee is made
// local instead: a path this function did not shape is not a path it will delete.
const OWN_DIR = new RegExp(`^${DIR_PREFIX}[A-Za-z0-9][A-Za-z0-9_-]{0,127}$`);

function removePromptTemplates(dir, log) {
  if (!dir) return;
  if (!OWN_DIR.test(path.basename(String(dir)))) {
    if (log && typeof log.warn === 'function') log.warn('[pi-prompts] refusing to remove a directory this module did not write');
    return;
  }
  try { fs.rmSync(dir, { recursive: true, force: true }); }
  catch (err) { if (log && typeof log.warn === 'function') log.warn(`[pi-prompts] cleanup failed: ${err.message}`); }
}

module.exports = {
  KINDS,
  OPTION_ID,
  buildPromptTemplate,
  writePromptTemplates,
  removePromptTemplates,
  hasArgumentSubstitution,
};
