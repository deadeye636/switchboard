// backends/pi/mcp-inject.js — hands a Pi session the app's own MCP server, and a project's external http servers,
// through Pi's built-in MCP client (#808, spec 34's quartet).
//
// Pi 1.1 added an MCP client that an extension feeds with `pi.registerMcpServer(name, config)`; the server is the
// session's only, and its tools are named `mcp__<server>__<tool>`, as the resources extension's own MCP section
// names its tools, so pi-native's approval gate asks about both alike. Measured (#808, spec 41 P6, Pi 1.5.2 on
// Windows): an http server with an `Authorization` header connects, lists and calls; a call is cancelled after
// 60 s (the client's default `timeout`), far above what the review and discovery tools take.
//
// Owner decision (#808, 2026-11-22): http rows go through Pi's client, stdio rows stay with the section
// (`./mcp-section.js`, which is built earlier in the spawn and works on every Pi version). So this emitter
// declares `http` only, and the composer keeps a stdio row away from it.
//
// What this writes is one ephemeral per-spawn extension, `pi-mcp-<tag>.ts` in the binding dir, loaded with `-e`
// (CLAUDE.md reflex 11 exemption). It carries the urls and the NAMES of environment variables, never a header
// value: the values ride the child's environment, and the extension reads each one when Pi loads it and deletes
// it from `process.env` right away, so the agent's shell never inherits a token (the section's rule).
//
// Pi evaluates an extension again on /reload and calls its default export once per RUNTIME (every /new, /resume and
// /fork), as the section's header says. The values read at the first evaluation are therefore kept on a registry
// symbol, and every call of the default export registers the servers again from there; a later evaluation finds
// the variables gone and keeps what it has.
//
// Pi reads `${VAR}` and a leading `!` in a header value as an expansion and a command (docs/mcp.md), so a value
// the extension hands over must hold neither; a row whose value does is skipped here and said by name. Pi treats two
// names that differ only in `-` and `_` as one server and rejects the second, so the emitter keeps the first and says
// so. A Pi without `registerMcpServer` (before 1.1) registers nothing and says so once per runtime, at
// `session_start`. One server Pi refuses is said too, and does not stop the others.
'use strict';

const fs = require('fs');
const path = require('path');

const NAME = /^[A-Za-z0-9_-]+$/;
const HEADER_NAME = /^[A-Za-z0-9-]+$/;
const FILE_PREFIX = 'pi-mcp-';
// The tag becomes part of a file name, and release deletes a file by that name: the same shape the resources
// extension refuses anything outside of (`./resources-extension.js`).
const TAG = /^[A-Za-z0-9][A-Za-z0-9_-]{0,127}$/;
const OWN_FILE = new RegExp(`^${FILE_PREFIX}[A-Za-z0-9][A-Za-z0-9_-]{0,127}\\.ts$`);
// The registry the extension keeps its header values on, across module evaluations.
const STATE_KEY = 'switchboard.pi.mcp-client';

/** The variable a header value rides in: by position, so two servers can never share one. */
function headerEnvVar(serverIndex, headerIndex) {
  return `SWITCHBOARD_PI_MCP_${serverIndex}_${headerIndex}`;
}

/** A value Pi would expand or run instead of sending. */
function expandsInPi(value) {
  const v = String(value);
  return v.includes('${') || v.trimStart().startsWith('!');
}

/** The key Pi compares server names by: `-` and `_` count as the same character. */
function piNameKey(name) {
  return String(name).replace(/-/g, '_');
}

/**
 * The generated extension. `servers` is `{ <name>: { url, headers: { <header>: <env var name> } } }`, written as one
 * JSON line so a test can read what was kept. Exposure is `direct` for every server: the section registers its
 * tools directly too, and the review tools must be in front of the model without a search.
 */
function extensionSource(servers) {
  return [
    '// Generated by Switchboard for one session (#808). Removed when the session ends.',
    `const SERVERS: any = ${JSON.stringify(servers)};`,
    '// Kept on a registry symbol: Pi evaluates this file again on /reload, and by then the variables are gone.',
    'const STATE: any = (() => {',
    `  const key = Symbol.for(${JSON.stringify(STATE_KEY)});`,
    '  const g: any = globalThis as any;',
    '  if (!g[key]) g[key] = { headers: {} };',
    '  const state = g[key];',
    '  for (const name of Object.keys(SERVERS)) {',
    '    const vars = SERVERS[name].headers || {};',
    '    if (!state.headers[name]) state.headers[name] = {};',
    '    for (const h of Object.keys(vars)) {',
    '      const v = process.env[vars[h]];',
    '      delete process.env[vars[h]];',
    '      if (typeof v === "string") state.headers[name][h] = v;',
    '    }',
    '  }',
    '  return state;',
    '})();',
    'function notify(ctx: any, text: string) {',
    '  try { if (ctx && ctx.ui && typeof ctx.ui.notify === "function") ctx.ui.notify(text, "warning"); } catch {}',
    '}',
    'export default function (pi: any) {',
    '  const names = Object.keys(SERVERS);',
    '  if (typeof pi.registerMcpServer !== "function") {',
    '    pi.on("session_start", (_event: any, ctx: any) => notify(ctx, "Switchboard could not give this session its MCP servers over http (" + names.join(", ") + "): this Pi has no MCP client. Pi 1.1 or newer has one."));',
    '    return;',
    '  }',
    '  const refused: string[] = [];',
    '  for (const name of names) {',
    '    try {',
    '      pi.registerMcpServer(name, { url: SERVERS[name].url, headers: { ...(STATE.headers[name] || {}) }, exposure: "direct" });',
    '    } catch { refused.push(name); }',
    '  }',
    '  if (refused.length) pi.on("session_start", (_event: any, ctx: any) => notify(ctx, "Pi refused the MCP server(s) " + refused.join(", ") + " that Switchboard gave this session."));',
    '}',
    '',
  ].join('\n');
}

/**
 * The hook. `cwd` is not used: the file goes into the binding dir, named by the terminal's tag.
 * Returns `{ args: ['-e', <file>], env, cleanup: { file } }` or `null` when no row can be emitted.
 */
function buildMcpInjection({ dir, tag, servers, log } = {}) {
  const lg = { debug() {}, info() {}, warn() {}, ...(log || {}) };
  if (!dir || typeof dir !== 'string' || !Array.isArray(servers) || !servers.length) return null;
  if (!TAG.test(String(tag || ''))) {
    lg.warn('[pi-mcp] the terminal tag cannot name a file; no MCP extension');
    return null;
  }

  const emitted = {};
  const keys = new Set();
  const env = {};
  let index = 0;
  for (const row of servers) {
    if (!row || !row.name || !NAME.test(String(row.name))) continue;
    if (row.transport !== 'http' || !row.url) continue;
    if (keys.has(piNameKey(row.name))) {
      lg.info(`[pi-mcp] skipped MCP server "${row.name}": Pi counts it as the same server as one already given`);
      continue;
    }
    const headers = row.headers && typeof row.headers === 'object' ? Object.entries(row.headers) : [];
    if (headers.some(([h]) => !HEADER_NAME.test(h))) {
      lg.info(`[pi-mcp] skipped MCP server "${row.name}": a header name cannot be passed`);
      continue;
    }
    if (headers.some(([, v]) => expandsInPi(v))) {
      lg.info(`[pi-mcp] skipped MCP server "${row.name}": a header value would be expanded or run by Pi`);
      continue;
    }
    const vars = {};
    headers.forEach(([h, v], j) => {
      const name = headerEnvVar(index, j);
      vars[h] = name;
      env[name] = String(v);
    });
    emitted[row.name] = { url: String(row.url), headers: vars };
    keys.add(piNameKey(row.name));
    index++;
  }
  if (!Object.keys(emitted).length) return null;

  const file = path.join(dir, `${FILE_PREFIX}${tag}.ts`);
  try {
    fs.mkdirSync(dir, { recursive: true });
    fs.writeFileSync(file, extensionSource(emitted), { mode: 0o600 });
  } catch (err) {
    lg.warn(`[pi-mcp] could not write the MCP extension: ${err && err.code}`);
    return null;
  }
  return { args: ['-e', file], env: Object.keys(env).length ? env : null, cleanup: { file } };
}

/** Removes this session's extension file only, and only one this module named. */
function releaseMcpInjection(cleanup, log) {
  const file = cleanup && cleanup.file;
  if (!file || !OWN_FILE.test(path.basename(file))) return;
  try {
    fs.rmSync(file, { force: true });
  } catch (err) {
    if (log && log.warn) log.warn(`[pi-mcp] could not remove the MCP extension: ${err && err.code}`);
  }
}

module.exports = { buildMcpInjection, releaseMcpInjection, headerEnvVar, extensionSource, STATE_KEY };
